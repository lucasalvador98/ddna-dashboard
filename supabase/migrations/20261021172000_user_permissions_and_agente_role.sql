-- ============================================================
-- user_permissions + rol "editor" → "agente"
--
-- Covers S5, S6, S9 and S10 of odd/tasks/acceso-roles.md.
--
--   * S5/S10 — the role with id 2 keeps its id (and therefore its
--     role_permissions and user_roles rows, both FKed on role_id) and is
--     renamed editor → agente. The UPDATE is guarded by name so a second
--     run is a no-op, and it is skipped when "agente" already exists (the
--     live DB was already renamed by hand before this file was written).
--
--   * S6 — user_permissions stores per-user ADDITIONS on top of the role
--     base ("agregados"): a row GRANTS a route (or edit) the role does not
--     have. It never revokes, because the merge in
--     src/lib/rbac-types.ts#mergePermissions is additive
--     (can_view = base OR extra). Revoking is done on the role base.
--
--   * S9 — role_permissions rows are seeded for the sidebar routes that
--     were missing from the matrix (/salud-adolescente, /encuestas,
--     /infancias) so the Roles screen can manage them per role. can_view
--     defaults to true because those three screens are already visible in
--     the sidebar today (auth enabled only hides what the matrix denies),
--     so seeding false would silently remove them for every role. The
--     admin hides them per role from /admin → Roles.
--
-- Idempotent: IF NOT EXISTS / DROP POLICY IF EXISTS / guarded UPDATE /
-- ON CONFLICT DO NOTHING. Safe to re-run.
--
-- Applies to: self-hosted production (supabase.ddna.com.ar).
-- Rollback: DROP TABLE public.user_permissions; and, if the rename must be
-- reverted, UPDATE public.roles SET name = 'editor' WHERE name = 'agente';
-- (role id 2 keeps its permission rows either way).
-- ============================================================

-- ── user_permissions ─────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.user_permissions (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  route      text NOT NULL,
  can_view   boolean NOT NULL DEFAULT false,
  can_edit   boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, route)
);

ALTER TABLE public.user_permissions ENABLE ROW LEVEL SECURITY;

-- ── RLS: same shape as the other RBAC tables ─────────────────────────────
-- Reads are public (the app resolves permissions server-side with the
-- service_role key; the service key bypasses RLS). Writes go through the
-- SECURITY DEFINER is_admin() helper — no inline user_roles subquery, so the
-- policy cannot recurse (see 20260923140000_fix_rbac_policy_recursion.sql).
DROP POLICY IF EXISTS "Lectura pública de user_permissions" ON public.user_permissions;
CREATE POLICY "Lectura pública de user_permissions" ON public.user_permissions
  FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Escritura admin user_permissions" ON public.user_permissions;
CREATE POLICY "Escritura admin user_permissions" ON public.user_permissions
  FOR ALL TO public USING (public.is_admin());

-- ── S5/S10: editor → agente (role id 2 keeps its rows) ───────────────────
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.roles WHERE name = 'editor')
     AND NOT EXISTS (SELECT 1 FROM public.roles WHERE name = 'agente') THEN
    UPDATE public.roles SET name = 'agente' WHERE name = 'editor';
  END IF;
END $$;

-- ── S9: the sidebar routes that were missing from the matrix ─────────────
INSERT INTO public.role_permissions (role_id, route, can_view, can_edit)
SELECT r.id, missing.route, true, false
FROM public.roles r
CROSS JOIN (
  VALUES ('/salud-adolescente'), ('/encuestas'), ('/infancias')
) AS missing(route)
ON CONFLICT (role_id, route) DO NOTHING;
